 WHERE code = 'CRS05' AND statuts_mc = '[]'::jsonb;

UPDATE sections SET statuts_mc = '["ASO", "BTS", "COS", "PERMANENCIER", "SMV"]'::jsonb
 WHERE code = 'CRS06' AND statuts_mc = '[]'::jsonb;

UPDATE sections SET statuts_mc = '["Albertville", "Modane", "Courchevel"]'::jsonb
 WHERE code = 'CRS73' AND statuts_mc = '[]'::jsonb;

-- Modifiable seulement par le poste lui-même, sur sa propre ligne — même
-- fonction `section_courante()` que le reste du cloisonnement (auth_rls.sql).
GRANT UPDATE (statuts_mc) ON sections TO authenticated;

DROP POLICY IF EXISTS maj_statuts_mc ON sections;
CREATE POLICY maj_statuts_mc ON sections
  FOR UPDATE TO authenticated
  USING (code = section_courante())
  WITH CHECK (code = section_courante());

-- ---------- effectifs du jour ----------
CREATE TABLE IF NOT EXISTS effectifs_mc (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_code   text NOT NULL REFERENCES sections(code),
  jour           date NOT NULL,
  role           text NOT NULL,
  nom            text NOT NULL,
  secouriste_id  bigint REFERENCES ref_secouristes(id),
  ordre          integer NOT NULL DEFAULT 0,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_effectifs_mc_jour ON effectifs_mc (section_code, jour);

ALTER TABLE effectifs_mc ENABLE ROW LEVEL SECURITY;

-- Même règle que les autres tables opérationnelles : le poste voit et gère
-- les effectifs de sa section et de ses postes rattachés (sections_visibles()).
DROP POLICY IF EXISTS par_section ON effectifs_mc;
CREATE POLICY par_section ON effectifs_mc
  FOR ALL TO authenticated
  USING (section_code = ANY (sections_visibles()))
  WITH CHECK (section_code = ANY (sections_visibles()));

GRANT SELECT, INSERT, UPDATE, DELETE ON effectifs_mc TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE effectifs_mc_id_seq TO authenticated;

COMMIT;

