 WHERE code = 'CRS66' AND adresse_rue IS NULL;

-- ---------- rôles par section ----------
ALTER TABLE sections ADD COLUMN IF NOT EXISTS statuts_mc jsonb NOT NULL DEFAULT '[]'::jsonb;

UPDATE sections SET statuts_mc = '["COS", "PERMANENCIER", "SOM", "SOM OPJ", "SOP", "SOP OPJ", "VERSOUD", "NUIT", "HUEZ", "ASTREINTE COS"]'::jsonb
 WHERE code = 'CRS38' AND statuts_mc = '[]'::jsonb;

