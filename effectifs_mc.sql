 WHERE code = 'CRS73' AND adresse_rue IS NULL;

UPDATE sections SET adresse_rue = '396 Av. Pierre Sauvaigo', code_postal = '06700', ville = 'SAINT-LAURENT-DU-VAR'
 WHERE code = 'CRS06' AND adresse_rue IS NULL;

